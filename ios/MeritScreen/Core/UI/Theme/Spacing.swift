import SwiftUI

/// Standardized layout grid spacing tokens (based on an 8pt system).
public enum MeritSpacing {
    /// 2pt
    public static let xxxSmall: CGFloat = 2
    /// 4pt
    public static let xxSmall: CGFloat = 4
    /// 8pt
    public static let xSmall: CGFloat = 8
    /// 12pt
    public static let small: CGFloat = 12
    /// 16pt (Standard margin)
    public static let medium: CGFloat = 16
    /// 20pt
    public static let large: CGFloat = 20
    /// 24pt
    public static let xLarge: CGFloat = 24
    /// 32pt
    public static let xxLarge: CGFloat = 32
    /// 40pt
    public static let xxxLarge: CGFloat = 40
    /// 48pt
    public static let huge: CGFloat = 48

    // Corner Radii
    public static let radiusSmall: CGFloat = 8
    public static let radiusMedium: CGFloat = 12
    public static let radiusLarge: CGFloat = 16
    public static let radiusXLarge: CGFloat = 24
    public static let radiusFull: CGFloat = 9999
}
